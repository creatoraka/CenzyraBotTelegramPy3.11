# Компилируем регулярные выражения
MAT_PATTERN = re.compile(
    r"(?<![а-яёa-z])(" + "|".join(MAT_ROOTS) + r")[а-яёa-z]*",
    re.IGNORECASE
)

BAD_WORD_PATTERN = re.compile(
    r"(?<![а-яёa-z])(" + "|".join(map(re.escape, BAD_WORDS)) + r")(?![а-яёa-z])",
    re.IGNORECASE
)

# ==================== ЦЕНЗУРА ====================

def censor_text(text: str) -> tuple[str, bool]:
    """Возвращает (отцензурированный_текст, найдено_ли_запрещённое)."""
    found = False

    def replace_match(match: re.Match) -> str:
        nonlocal found
        found = True
        word = match.group(0)
        return word[0] + "*" * (len(word) - 1)

    text = MAT_PATTERN.sub(replace_match, text)
    text = BAD_WORD_PATTERN.sub(replace_match, text)
    return text, found

