def censor_text(text: str) -> tuple[str, bool]:
    found = False

    def replace_match(match: re.Match) -> str:
        nonlocal found
        found = True
        word = match.group(0)
        return word[0] + "*" * (len(word) - 1)

    text = MAT_PATTERN.sub(replace_match, text)
    text = BAD_WORD_PATTERN.sub(replace_match, text)
    return text, found

